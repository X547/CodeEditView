#!/usr/bin/env python3
"""Embed text files as a C++ string constant.

Usage: embed_text.py <output.inc> <constant name> <input>...

The inputs are concatenated in order.
"""

import sys

DELIMITER = "embed"


def main():
	if len(sys.argv) < 4:
		print(__doc__.strip(), file=sys.stderr)
		return 1
	output, name, inputs = sys.argv[1], sys.argv[2], sys.argv[3:]
	text = ""
	for path in inputs:
		with open(path, encoding="utf-8") as file:
			text += file.read()
	if ")" + DELIMITER + '"' in text:
		print(f"embed_text.py: delimiter occurs in input", file=sys.stderr)
		return 1
	with open(output, "w", encoding="utf-8", newline="\n") as file:
		file.write(f"// Generated by tools/embed_text.py. Do not edit.\n\n")
		file.write(f"static constexpr const char {name}[] = R\"{DELIMITER}(")
		file.write(text)
		file.write(f"){DELIMITER}\";\n")
	return 0


if __name__ == "__main__":
	sys.exit(main())
