#!/usr/bin/env python3
"""Generate src/unicode/CharWidthTable.inc from the Unicode Character Database.

Usage: gen_char_width.py <ucd cache dir> <output file>

Missing UCD files are downloaded into the cache directory.
"""

import os
import re
import sys
import urllib.request

UCD_URL = "https://www.unicode.org/Public/UCD/latest/ucd/"
UCD_FILES = {
	"EastAsianWidth.txt": "EastAsianWidth.txt",
	"DerivedGeneralCategory.txt": "extracted/DerivedGeneralCategory.txt",
	"emoji-data.txt": "emoji/emoji-data.txt",
}

# Must match CharClass and flags in src/unicode/CharWidth.h.
NARROW, WIDE, AMBIGUOUS, COMBINING, FORMAT, CONTROL = range(6)
CLASS_MASK = 0x0f
FLAG_EMOJI = 0x10
FLAG_EMOJI_PRESENTATION = 0x20

MAX_CODE_POINT = 0x10ffff

LINE_RE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)")
MISSING_RE = re.compile(r"^#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*([A-Za-z_]+)")
VERSION_RE = re.compile(r"^#\s*EastAsianWidth-([0-9.]+)\.txt")


def fetch(cache_dir):
	os.makedirs(cache_dir, exist_ok=True)
	paths = {}
	for name, remote in UCD_FILES.items():
		path = os.path.join(cache_dir, name)
		if not os.path.exists(path):
			print("downloading", UCD_URL + remote)
			urllib.request.urlretrieve(UCD_URL + remote, path)
		paths[name] = path
	return paths


def parse(path, include_missing=False):
	with open(path, encoding="utf-8") as file:
		for line in file:
			if include_missing:
				match = MISSING_RE.match(line)
				if match:
					yield int(match[1], 16), int(match[2], 16), match[3], True
					continue
			match = LINE_RE.match(line)
			if match:
				first = int(match[1], 16)
				last = int(match[2], 16) if match[2] else first
				yield first, last, match[3], False


def read_version(path):
	with open(path, encoding="utf-8") as file:
		for line in file:
			match = VERSION_RE.match(line)
			if match:
				return match[1]
	return "unknown"


def build(paths):
	classes = bytearray(MAX_CODE_POINT + 1)

	# East Asian Width: defaults for unassigned ranges first, then explicit data.
	entries = list(parse(paths["EastAsianWidth.txt"], include_missing=True))
	for explicit in (False, True):
		for first, last, value, missing in entries:
			if missing == explicit:
				continue
			cls = WIDE if value in ("W", "F") else AMBIGUOUS if value == "A" else NARROW
			classes[first:last + 1] = bytes([cls]) * (last - first + 1)

	for first, last, category, _ in parse(paths["DerivedGeneralCategory.txt"]):
		if category in ("Mn", "Me"):
			cls = COMBINING
		elif category in ("Cf", "Zl", "Zp"):
			cls = FORMAT
		elif category == "Cc":
			cls = CONTROL
		else:
			continue
		classes[first:last + 1] = bytes([cls]) * (last - first + 1)

	# Conjoining Hangul jamo vowels and trailing consonants, zero width joiner and
	# emoji tag characters extend the preceding cluster.
	for first, last in ((0x1160, 0x11ff), (0xd7b0, 0xd7ff), (0x200d, 0x200d), (0xe0020, 0xe007f)):
		classes[first:last + 1] = bytes([COMBINING]) * (last - first + 1)

	for first, last, prop, _ in parse(paths["emoji-data.txt"]):
		if prop == "Emoji":
			flag = FLAG_EMOJI
		elif prop == "Emoji_Presentation":
			flag = FLAG_EMOJI_PRESENTATION
		else:
			continue
		for code_point in range(first, last + 1):
			info = classes[code_point] | flag
			if flag == FLAG_EMOJI_PRESENTATION and info & CLASS_MASK in (NARROW, AMBIGUOUS):
				info = (info & ~CLASS_MASK) | WIDE
			classes[code_point] = info

	ranges = []
	for code_point, info in enumerate(classes):
		if not ranges or ranges[-1][1] != info:
			ranges.append((code_point, info))
	return ranges


def write(path, ranges, version):
	with open(path, "w", encoding="utf-8", newline="\n") as file:
		file.write(f"// Generated by tools/gen_char_width.py from Unicode {version}. Do not edit.\n")
		file.write("// Entries: first code point of a range, class | flags (see CharWidth.h).\n")
		file.write("\n")
		file.write(f"static constexpr const char *kUnicodeVersion = \"{version}\";\n")
		file.write("\n")
		file.write("static constexpr CharWidthRange kCharWidthRanges[] = {\n")
		for first, info in ranges:
			file.write(f"\t{{0x{first:06x}, 0x{info:02x}}},\n")
		file.write("};\n")


def main():
	if len(sys.argv) != 3:
		print(__doc__.strip(), file=sys.stderr)
		return 1
	paths = fetch(sys.argv[1])
	ranges = build(paths)
	write(sys.argv[2], ranges, read_version(paths["EastAsianWidth.txt"]))
	print(f"{len(ranges)} ranges written to {sys.argv[2]}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
